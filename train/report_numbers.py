"""Write numbers.tex (LaTeX macros) and summary.json for the Chinchilla report from the run logs and probe."""
import argparse
import json
import os
import statistics

VARIANTS = ['baseline', 'approach_1', 'approach_2']
PREFIX = {'baseline': 'Base', 'approach_1': 'One', 'approach_2': 'Two'}


def load(path):
    val, train = [], []
    with open(path) as f:
        for line in f:
            r = json.loads(line)
            (val if 'val_loss' in r else train).append(r)
    return val, train


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--runs', required=True)
    ap.add_argument('--probe', required=True)
    ap.add_argument('--out', required=True)
    args = ap.parse_args()
    probe = json.load(open(os.path.join(args.probe, 'collapse_probe.json')))
    ref = json.load(open(os.path.join(args.runs, 'openai_gpt2_124M.json')))['val_loss']
    me = json.load(open(os.path.join(args.probe, 'matched_evals.json')))
    m = {'RefLoss': f'{ref:.3f}', 'UniCE': f'{probe["unigram_val_ce"]:.3f}',
         'RefFour': f'{me["val4M"]["openai_gpt2_124M"]:.3f}', 'UniFour': f'{me["val4M"]["unigram"]:.3f}',
         'BaseFour': f'{me["val4M"]["baseline_final"]:.3f}',
         'OneTwenty': f'{me["val20M"]["approach_1_step3000"]:.3f}', 'TwoTwenty': f'{me["val20M"]["approach_2_step3000"]:.3f}',
         'OneFour': f'{me["val4M"]["approach_1_step3000"]:.3f}', 'TwoFour': f'{me["val4M"]["approach_2_step3000"]:.3f}'}
    summary = {'openai_gpt2_124M_pretrained_val_loss': ref, 'unigram_val_ce': probe['unigram_val_ce'],
               'matched_evals': me, 'runs': {}}
    vals = {}
    for v in VARIANTS:
        val, train = load(os.path.join(args.runs, v, 'log.jsonl'))
        vals[v] = {r['step']: r['val_loss'] for r in val if not r.get('final')}
        final = next((r for r in val if r.get('final')), None)
        last_step = train[-1]['step'] + 1
        p = PREFIX[v]
        m[f'{p}Final'] = f'{final["val_loss"]:.3f}' if final else '--'
        m[f'{p}Last'] = f'{val[-1]["val_loss"]:.3f}'
        m[f'{p}Stop'] = str(last_step)
        m[f'{p}Tokens'] = f'{last_step * 524288 / 1e9:.2f}B'
        m[f'{p}Plateau'] = f'{statistics.mean(r["train_loss"] for r in train if 200 <= r["step"] <= 3700):.3f}'
        key = next(k for k in probe['models'] if k.startswith(v + '@step'))
        pm, pi = probe['models'][key], probe['models'][f'{v}@init']
        norms = [r['norm'] for r in pm['layers']]
        norms_i = [r['norm'] for r in pi['layers']]
        m[f'{p}KL'] = f'{pm["kl_to_unigram"]:.4f}'
        m[f'{p}Growth'] = f'{(norms[-1] / norms[2]) ** 0.1:.1f}'
        m[f'{p}GrowthInit'] = f'{(norms_i[-1] / norms_i[2]) ** 0.1:.2f}'
        e = f'{norms[-1]:.1e}'.split('e')
        m[f'{p}NormEnd'] = f'${e[0]}\\times10^{{{int(e[1])}}}$' if norms[-1] >= 1e4 else f'{norms[-1]:.0f}'
        summary['runs'][v] = {'steps_trained': last_step, 'tokens_trained': last_step * 524288,
                              'final_val_loss_20M': final['val_loss'] if final else None,
                              'last_val_loss': val[-1]['val_loss'], 'last_val_step': val[-1]['step'],
                              'probe_checkpoint': key, 'kl_to_unigram': pm['kl_to_unigram'],
                              'status': 'completed' if final else 'stopped (collapsed)'}
    rows = []
    for s in sorted(vals['baseline']):
        if s % 500 and s != 250:
            continue
        cells = [f'{vals[v][s]:.3f}' if s in vals[v] else '--' for v in VARIANTS]
        rows.append(f'{s} & {s * 524288 / 1e9:.2f}B & ' + ' & '.join(cells) + r' \\')
    if summary['runs']['baseline']['final_val_loss_20M'] is not None:
        rows.append(r'\midrule')
        rows.append(f'{summary["runs"]["baseline"]["steps_trained"]} (final, 20M val) & 2.50B & '
                    f'{summary["runs"]["baseline"]["final_val_loss_20M"]:.3f} & -- & -- \\\\')
    m['ValTable'] = '\n'.join(rows)
    with open(os.path.join(args.out, 'numbers.tex'), 'w') as f:
        f.write('% auto-generated by train/report_numbers.py\n')
        for k, val in m.items():
            f.write(f'\\newcommand{{\\{k}}}{{{val}}}\n')
    with open(os.path.join(args.out, 'data', 'summary.json'), 'w') as f:
        json.dump(summary, f, indent=2)
    print(open(os.path.join(args.out, 'numbers.tex')).read())


if __name__ == '__main__':
    main()
